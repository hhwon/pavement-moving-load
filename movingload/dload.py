"""
Generate the Fortran user subroutine that drives the moving tyre.

Abaqus has no built-in "load that translates along the mesh", so the tyre
print is imposed through user subroutines evaluated at every surface
integration point and every increment:

    DLOAD      vertical pressure   — returns P0 inside the print, 0 outside
    UTRACLOAD  tangential traction — returns magnitude mu*P0 and the unit
                                     direction (0, 0, ±1) along the surface

`UTRACLOAD` is emitted only when the case has `mu > 0`; a purely vertical
case gets a `DLOAD`-only file, which is what Abaqus expects when the deck
carries no `*DSLOAD`.

The tyre centre moves linearly:

    z_c(t) = z_start + (z_end - z_start) * t / t_final

with `z_start` / `z_end` outside the domain so the tyre enters and leaves
cleanly.  Parameters are written into a Fortran `PARAMETER` block, so a
speed or pressure change needs only a recompile — no new `.inp`, as long as
the mesh still resolves the print.
"""
from __future__ import annotations

from pathlib import Path

from .config import CaseConfig, Motion, Tyre


_HEADER = """C     -----------------------------------------------------------------
C     Moving single-tyre surface load on a 3-D half-pavement model.
C     Generated by movingload.dload — edit the generator, not this file.
C
C     Case      : {case_id}
C     Motion    : z_c(t) = {z_start} + ({z_end} - ({z_start})) * t / {t_final}
C     Tyre      : centre x = {x_centre} m, radius {radius} m, p = {p_mpa} MPa
C     Force     : pi*R^2*p = {force_kn} kN per tyre print
{traction_note}C     -----------------------------------------------------------------
"""

_TRACTION_NOTE = """C     Traction  : mu = {mu}, direction {direction} (MU_SIGN = {mu_sign})
C
C     DLOAD returns the vertical pressure (load type P3NU); UTRACLOAD
C     returns the tangential traction magnitude and its unit direction
C     (load type TRVEC3NU).  The footprint and motion are identical for
C     both; only the surface load gains a tangential component.
"""

_VERTICAL_NOTE = """C     Traction  : none (vertical load only)
"""

_DLOAD = """      SUBROUTINE DLOAD(F,KSTEP,KINC,TIME,NOEL,NPT,LAYER,KSPT,
     1                 COORDS,JLTYP,SNAME)
C
      INCLUDE 'ABA_PARAM.INC'
      DIMENSION TIME(2), COORDS(3)
      CHARACTER*80 SNAME
C
      DOUBLE PRECISION P0, R, X_TYRE, ZSTART, ZEND, TFINAL
      DOUBLE PRECISION X, Z, ZC, T, DIST2
C
{params}
C
      T  = TIME(1)
      ZC = ZSTART + (ZEND - ZSTART) * T / TFINAL
      X = COORDS(1)
      Z = COORDS(3)
      DIST2 = (X - X_TYRE) * (X - X_TYRE) + (Z - ZC) * (Z - ZC)
C
      IF (DIST2 .LE. R * R) THEN
         F = P0
      ELSE
         F = 0.0D0
      END IF
      RETURN
      END
"""

_UTRACLOAD = """C
C     -----------------------------------------------------------------
      SUBROUTINE UTRACLOAD(ALPHA,T_USER,KSTEP,KINC,TIME,NOEL,NPT,
     1                     COORDS,DIRCOS,JLTYP,SNAME)
C
      INCLUDE 'ABA_PARAM.INC'
      DIMENSION TIME(2), COORDS(3), DIRCOS(3,3), T_USER(3)
      CHARACTER*80 SNAME
C
      DOUBLE PRECISION P0, R, X_TYRE, MU, MU_SIGN
      DOUBLE PRECISION ZSTART, ZEND, TFINAL
      DOUBLE PRECISION X, Z, ZC, T, DIST2
C
{params}
C
      T  = TIME(1)
      ZC = ZSTART + (ZEND - ZSTART) * T / TFINAL
      X = COORDS(1)
      Z = COORDS(3)
      DIST2 = (X - X_TYRE) * (X - X_TYRE) + (Z - ZC) * (Z - ZC)
C
      T_USER(1) = 0.0D0
      T_USER(2) = 0.0D0
      T_USER(3) = MU_SIGN
C
      IF (DIST2 .LE. R * R) THEN
         ALPHA = MU * P0
      ELSE
         ALPHA = 0.0D0
      END IF
      RETURN
      END
"""


def _fortran_double(value: float) -> str:
    """Render a Python float as a Fortran DOUBLE PRECISION literal."""
    text = repr(float(value))
    if "e" in text or "E" in text:
        mantissa, exponent = text.lower().split("e")
        if "." not in mantissa:
            mantissa += ".0"
        return f"{mantissa}D{int(exponent)}"
    if "." not in text:
        text += ".0"
    return f"{text}D0"


def _param_block(pairs: list[tuple[str, float]]) -> str:
    width = max(len(name) for name, _ in pairs)
    return "\n".join(
        f"      PARAMETER ({name:<{width}} = {_fortran_double(v)})"
        for name, v in pairs
    )


def source(tyre: Tyre, motion: Motion, case_id: str = "case") -> str:
    """Return the complete Fortran source for one case."""
    common = [
        ("P0", tyre.pressure),
        ("R", tyre.radius),
        ("X_TYRE", tyre.x_centre),
        ("ZSTART", motion.z_start),
        ("ZEND", motion.z_end),
        ("TFINAL", motion.t_final),
    ]

    if motion.horizontal:
        direction = "+z (acceleration)" if motion.mu_sign > 0 else "-z (braking)"
        note = _TRACTION_NOTE.format(mu=motion.mu, direction=direction,
                                     mu_sign=f"{motion.mu_sign:+.1f}")
    else:
        note = _VERTICAL_NOTE

    text = _HEADER.format(
        case_id=case_id,
        z_start=motion.z_start, z_end=motion.z_end, t_final=motion.t_final,
        x_centre=tyre.x_centre, radius=tyre.radius,
        p_mpa=f"{tyre.pressure / 1e6:g}", force_kn=f"{tyre.force / 1e3:.2f}",
        traction_note=note,
    )
    text += _DLOAD.format(params=_param_block(common))

    if motion.horizontal:
        traction = common[:3] + [("MU", motion.mu), ("MU_SIGN", motion.mu_sign)] \
                   + common[3:]
        text += _UTRACLOAD.format(params=_param_block(traction))
    return text


def build(cfg: CaseConfig, out_dir: str | Path, filename: str = "dload.f") -> dict:
    """Write the subroutine into `out_dir` and return a small info dict."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / filename
    path.write_text(source(cfg.tyre, cfg.motion, cfg.case_id), encoding="utf-8")
    return {
        "path": str(path),
        "has_utracload": cfg.motion.horizontal,
        "mu": cfg.motion.mu,
        "mu_sign": cfg.motion.mu_sign,
    }
